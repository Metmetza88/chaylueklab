export function sampleGroups(rows: SampleRow[]) {
  return [...new Set(rows.map((row) => row[2]))].map((name) => {
    const values = rows.filter((row) => row[2] === name);
    return {
      name,
      average: Math.round(
        values.reduce((sum, row) => sum + row[3], 0) / values.length,
      ),
    };
  });
}
